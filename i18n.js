let language = new URLSearchParams(location.search).get('lang') === 'en' ? 'en' : 'es';
export const t = key => messages[language][key] ?? messages.es[key] ?? key;

function applyLanguage(nextLanguage, updateUrl = true) {
  language = nextLanguage === 'en' ? 'en' : 'es';
  document.documentElement.lang = language;
  document.title = t('page.title');
  document.querySelector('meta[name="description"]').content = t('page.description');
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  document.querySelectorAll('[data-language]').forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.language === language));
  });
  const status = document.querySelector('[data-model-message]');
  if (status) status.textContent = t(status.dataset.modelMessage);
  if (updateUrl) {
    const url = new URL(location.href);
    url.searchParams.set('lang', language);
    history.replaceState(null, '', url);
  }
  dispatchEvent(new Event('arise:languagechange'));
}

export function initLanguage() {
  applyLanguage(language, false);
  document.querySelectorAll('[data-language]').forEach(button => {
    button.addEventListener('click', () => applyLanguage(button.dataset.language));
  });
}
